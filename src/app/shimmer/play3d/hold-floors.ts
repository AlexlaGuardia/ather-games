// hold-floors.ts — THE HOLD's floor plans. THIS is the file to edit when the layout changes.
//
// ── THE RULER (Alex 2026-09-25) ────────────────────────────────────────────────────────────────
// One character = one BLOCK = 1 world unit ≈ 1 metre (the authoring body stands 1.75). A keeper runs
// 6.5 blocks a second, so a 50 × 80 floor is ~8 × 12 seconds of running end to end.
// Floors are STOREY blocks apart (`hold-building.ts`), stacked straight over each other: every floor
// here is a 50 × 80 plate with its own walls; the bottom floor opens west and east onto 50 × 50 gardens.
//
// Legend (every floor):
//   ' ' nothing — the air outside, or a stairwell's hole over a ramp below
//   '.' floor · '#' wall (floor to ceiling; round every stairwell — a rail there gets jumped) · '|' a low rail (waist-high; the roof's and gardens' edge)
//   'w' a window in an outside wall — the flooded climb the face to it and tear its seals
//   '^' 'v' '<' '>' a STAIR FLIGHT up to the floor above, drawn on the LOWER floor. The arrow points UPHILL.
//   'o' a flat LANDING between two flights — how a stair turns a corner.
//       A stair is one path: flight, landing, flight… Its flights together must be at least STOREY long
//       (no steeper than one block up per block along), the first flight's low end must face floor, the
//       last flight's top end must face floor on the floor above, and the floor above is ' ' over all of it.
//   'u' a rooftop unit — chest-high cover you can climb onto · 'p' floor painted as the landing pad
//   an uppercase letter: a GATE (bought open; see `HOLD_TUNING.gateCost`) — except these fixtures:
//   '@' where you stand · 'X' the way out · 'R' the wall rack · 'F' the mana font · 'H' the draught cache
// Rooms are not declared: walls and gates split each floor into regions, a ramp joins the regions at its
// two ends, and a gate opens the regions on both of its sides. The region under '@' is open at the start.

export interface FloorPart {
  /** top-left of this plan in the hold's grid */
  x: number
  z: number
  rows: readonly string[]
  /** a tint for this part's floor (default: the floor's own) */
  tone?: 'garden'
}
export interface FloorDef {
  name: string
  parts: FloorPart[]
  /** open to the sky — no roof over this floor (the rooftop) */
  open?: boolean
}

