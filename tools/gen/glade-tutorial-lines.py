#!/usr/bin/env python3
"""M68: generate src/app/shimmer/open/ather/glade-tutorial-lines.ts from the SIGNED lines in
athernyx CANON/game/shimmer-quest-glade-tutorial.md (rev1). Lines are wired by id, verbatim; re-run after a canon revision."""
import re, json, subprocess
SRC = '/root/athernyx/CANON/game/shimmer-quest-glade-tutorial.md'
OUT = '/root/ather-games/src/app/shimmer/open/ather/glade-tutorial-lines.ts'
rev = subprocess.run(['git', '-C', '/root/athernyx', 'log', '-1', '--format=%h', '--', 'CANON/game/shimmer-quest-glade-tutorial.md'], capture_output=True, text=True).stdout.strip()
lines = {}
for raw in open(SRC, encoding='utf-8'):
    m = re.match(r'^- `([a-z0-9_.]+)`\s*(?:\[[^\]]*\]\s*)?(.*)$', raw.rstrip('\n'))
    if not m: continue
    lid, rest = m.group(1), m.group(2).strip()
    rest = re.sub(r'\s*\*\([^)]*\)\*\s*$', '', rest)          # trailing *(signed, ...)* notes
    if rest.startswith('> '): lines[lid] = {'who': None, 'text': rest[2:].strip(), 'choice': True}; continue
    sm = re.match(r'^([A-Z][A-Z ]+):\s*(.*)$', rest)
    if sm: lines[lid] = {'who': sm.group(1).title(), 'text': sm.group(2).strip()}
    else: lines[lid] = {'who': None, 'text': rest}
src_lines = open(SRC, encoding='utf-8').read().split('\n')
for i, raw in enumerate(src_lines):                            # overlay: `- `id` (replaces ...)` then the text bold on the next line
    m = re.match(r'^- `([a-z0-9_.]+)` \(replaces', raw)
    if m and i + 1 < len(src_lines):
        nm = re.match(r'^\s+\*\*(.+)\*\*\s*$', src_lines[i + 1])
        if nm: lines[m.group(1)] = {'who': None, 'text': nm.group(1)}
for raw in open(SRC, encoding='utf-8'):                        # quest titles: [quest log] `id` **Title**
    m = re.match(r'^\[quest log\] `([a-z0-9_.]+)` \*\*(.+)\*\*', raw)
    if m: lines[m.group(1)] = {'who': None, 'text': m.group(2)}; continue
    m = re.match(r'^\[quest log\] `([a-z0-9_.]+)` ([^*].*)$', raw.rstrip('\n'))   # M70: a plain quest-log step (quest.m70.after)
    if m: lines[m.group(1)] = {'who': None, 'text': m.group(2).strip()}
body = ',\n'.join(f'  {json.dumps(k)}: {json.dumps(v, ensure_ascii=False)}' for k, v in lines.items())
open(OUT, 'w', encoding='utf-8').write(f"""// GENERATED by tools/gen/glade-tutorial-lines.py from athernyx CANON/game/shimmer-quest-glade-tutorial.md ({rev}).
// The SIGNED Glade tutorial lines (@lark, Alex), keyed by their ids. Do not edit by hand: fix canon, re-run the script.
export interface Line {{ who: string | null; text: string; choice?: true }}
export const GLADE_LINES: Readonly<Record<string, Line>> = {{
{body},
}}
/** A line's text by id; throws on a missing id so a canon rename is loud, never a blank bubble. */
export function line(id: string): string {{ const l = GLADE_LINES[id]; if (!l) throw new Error(`glade line missing: ${{id}}`); return l.text }}
""")
print(len(lines), 'lines', rev)
